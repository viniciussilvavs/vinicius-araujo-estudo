#União de conceitos

#Todas as estruturas podem ser usadas separadamente,
#mas em um programa "real", vamos unindo todas essas estruturas para criarmos 
#os cenários que precisamos para resolver um problema.

#Exemplo

#Você quer saber se uma palavra contém a letra "y"

palavra = "python" 
letraprocurada = "y"

for letra in palavra:
    if letra == letraprocurada:
        print("Essa palavra tem a letra", letraprocurada)
     










